// Bunker Template: 22 width x 16 height
// Creates the classic dome arch shape with an inner hollow arch at bottom
function createBunkerTemplate() {
  const width = 22;
  const height = 16;
  const grid = [];
  
  for (let y = 0; y < height; y++) {
    const row = [];
    for (let x = 0; x < width; x++) {
      let solid = 1;

      // Top corner rounded cutouts
      if (y === 0 && (x < 4 || x >= width - 4)) solid = 0;
      else if (y === 1 && (x < 3 || x >= width - 3)) solid = 0;
      else if (y === 2 && (x < 2 || x >= width - 2)) solid = 0;
      else if (y === 3 && (x < 1 || x >= width - 1)) solid = 0;

      // Bottom center arch cutout
      if (y >= 10) {
        const archWidth = 8;
        const archStart = Math.floor((width - archWidth) / 2);
        const archEnd = archStart + archWidth;
        
        if (x >= archStart && x < archEnd) {
          if (y >= 12) solid = 0;
          else if (y === 11 && (x > archStart && x < archEnd - 1)) solid = 0;
          else if (y === 10 && (x > archStart + 1 && x < archEnd - 2)) solid = 0;
        }
      }

      row.push(solid);
    }
    grid.push(row);
  }
  return grid;
}

// Helper to draw a pixel matrix to an HTML5 canvas context
function drawPixelMatrix(ctx, matrix, x, y, pixelSize, color) {
  ctx.fillStyle = color;
  for (let r = 0; r < matrix.length; r++) {
    for (let c = 0; c < matrix[r].length; c++) {
      if (matrix[r][c]) {
        ctx.fillRect(
          Math.floor(x + c * pixelSize),
          Math.floor(y + r * pixelSize),
          pixelSize,
          pixelSize
        );
      }
    }
  }
}

